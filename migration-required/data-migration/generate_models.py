"""Generate an exact, read-only Django compatibility layer from reviewed DDL.

The native SQL restore owns physical DDL, defaults, indexes, triggers and views.
No artificial primary keys or guessed relationships are introduced.
"""
import json
import keyword
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
META = ROOT.parent / 'reports/project-understanding/database-verified/schema-metadata.json'
OUT = ROOT / 'backend' / 'legacy'


def identifier(name):
    name = re.sub(r'[^a-zA-Z0-9_]', '_', name).lower()
    if not name or name[0].isdigit() or name.startswith('_'):
        name = 'column_' + name
    if keyword.iskeyword(name) or name in {'pk', 'objects', 'save', 'delete', 'check', 'clean', 'validate_unique'}:
        name += '_field'
    while '__' in name:
        name = name.replace('__', '_')
    return name


def generate():
    data = json.loads(META.read_text())
    tables = data['tables']
    names = {(t['schema'], t['name']): 'T' + ''.join(x.title() for x in re.split('[^a-zA-Z0-9]+', t['name'])) for t in tables}
    fields = {}
    for t in tables:
        mapping = {c['name']: identifier(c['name']) for c in t['columns']}
        if len(set(mapping.values())) != len(mapping):
            raise ValueError('Field-name collision: ' + t['name'])
        fields[t['schema'], t['name']] = mapping
    report = {'source_sha256': data['sha256'], 'schemas': {}, 'tables': [], 'objects': data['objects']}
    for schema in data['schemas']:
        path = OUT / schema
        path.mkdir(parents=True, exist_ok=True)
        (path / '__init__.py').write_text('')
        lines = ['# Generated by migration-required/data-migration/generate_models.py. Read-only compatibility mapping.\n',
                 'from django.db import models\nfrom legacy.base import ReadOnlyModel, LegacyTable\n\n']
        stats = {'tables': 0, 'orm_models': 0, 'keyless_readers': 0, 'composite_keys': 0}
        schema_names = set()
        for t in (t for t in tables if t['schema'] == schema):
            name = names[schema, t['name']]
            if name in schema_names:
                raise ValueError('Model-name collision: ' + name)
            schema_names.add(name)
            mapping = fields[schema, t['name']]
            pk = next((i['columns'] for i in t['indexes'] if i['kind'] == 'PRIMARY KEY'), [])
            stats['tables'] += 1
            report['tables'].append({'schema': schema, 'table': t['name'], 'class': name, 'fields': mapping,
                                     'primary_key': pk, 'access': 'orm' if pk else 'keyless_reader',
                                     'foreign_keys': t['foreignKeys'], 'indexes': t['indexes'],
                                     'columns': t['columns'], 'engine': t['engine'], 'charset': t['charset']})
            if not pk:
                stats['keyless_readers'] += 1
                lines.append(f"{name} = LegacyTable({schema!r}, {t['name']!r}, {list(mapping)!r})\n\n")
                continue
            stats['orm_models'] += 1
            lines.append(f'class {name}(ReadOnlyModel):\n')
            if len(pk) > 1:
                stats['composite_keys'] += 1
                lines.append('    pk = models.CompositePrimaryKey(' + ', '.join(repr(mapping[c]) for c in pk) + ')\n')
            for c in t['columns']:
                col = c['name']
                typ = c['sqlType'].lower()
                args = [f'db_column={col!r}']
                primary = len(pk) == 1 and pk[0] == col
                args.append('primary_key=True' if primary else f"null={c['nullable']!r}")
                match = re.search(r'\((\d+)(?:,(\d+))?\)', typ)
                if typ.startswith('varchar'):
                    kind = 'CharField'
                    args.append(f'max_length={int(match[1])}')
                elif typ.startswith(('longtext', 'text')):
                    kind = 'TextField'
                elif typ.startswith('longblob'):
                    kind = 'BinaryField'
                elif typ.startswith('decimal'):
                    kind = 'DecimalField'
                    args += [f'max_digits={int(match[1])}', f'decimal_places={int(match[2] or 0)}']
                elif typ.startswith('double'):
                    kind = 'FloatField'
                elif typ.startswith(('datetime', 'timestamp')):
                    kind = 'DateTimeField'
                elif typ.startswith('date'):
                    kind = 'DateField'
                elif typ.startswith(('bigint', 'int', 'tinyint')):
                    kind = 'BigIntegerField' if typ.startswith('bigint') else 'IntegerField'
                    if c['autoIncrement'] and primary:
                        kind = 'BigAutoField' if typ.startswith('bigint') else 'AutoField'
                else:
                    raise ValueError('Unmapped SQL type: ' + typ)
                # Preserve actual declared foreign keys only, without guessing business relationships.
                fk = next((f for f in t['foreignKeys'] if f['columns'] == [col]), None)
                if fk:
                    target_schema = fk.get('referencedSchema') or schema
                    target_table = fk['referencedTable']
                    target_field = fields[target_schema, target_table][fk['referencedColumns'][0]]
                    target_name = names[target_schema, target_table]
                    kind = 'ForeignKey'
                    args = [repr(f'legacy_{target_schema}.{target_name}'), 'on_delete=models.DO_NOTHING',
                            f'db_column={col!r}', f'to_field={target_field!r}', "related_name='+'",
                            f"null={c['nullable']!r}"] + (['primary_key=True'] if primary else [])
                    # Keep original scalar access via <column>_id for these generated fields.
                lines.append(f"    {mapping[col]} = models.{kind}({', '.join(args)})\n")
            lines.append(f"    class Meta:\n        managed = False\n        app_label = 'legacy_{schema}'\n        db_table = {t['name']!r}\n\n")
        (path / 'models.py').write_text(''.join(lines))
        (path / 'apps.py').write_text(f"from django.apps import AppConfig\n\nclass LegacyConfig(AppConfig):\n    name = 'legacy.{schema}'\n    label = 'legacy_{schema}'\n")
        report['schemas'][schema] = stats
    (ROOT / 'migration-required' / 'data-migration' / 'mapping-catalog.json').write_text(json.dumps(report, indent=2))
    print(json.dumps(report['schemas'], indent=2))


if __name__ == '__main__':
    generate()
